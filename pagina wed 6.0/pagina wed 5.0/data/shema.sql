BEGIN;

DO $$
BEGIN
    CREATE ROLE turilli_app NOLOGIN;
EXCEPTION
    WHEN duplicate_object THEN NULL;
END;
$$;

CREATE TYPE tipo_entrega AS ENUM ('domicilio', 'recogida');
CREATE TYPE estado_pedido AS ENUM (
    'pendiente',
    'confirmado',
    'preparando',
    'en_camino',
    'entregado',
    'cancelado'
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT categorias_nombre_valido CHECK (nombre IN ('ensalada', 'pasta', 'pizza', 'postre'))
);

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL UNIQUE,
    descripcion TEXT NOT NULL DEFAULT '',
    precio_cop INTEGER NOT NULL CHECK (precio_cop > 0),
    imagen TEXT NOT NULL,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(30) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
    tipo_entrega tipo_entrega NOT NULL,
    direccion VARCHAR(180),
    barrio VARCHAR(100),
    fecha_deseada DATE,
    hora_deseada TIME,
    observaciones VARCHAR(500) NOT NULL DEFAULT '',
    medio_pago VARCHAR(80) NOT NULL,
    total_cop BIGINT NOT NULL CHECK (total_cop > 0),
    estado estado_pedido NOT NULL DEFAULT 'pendiente',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pedidos_direccion_domicilio CHECK (
        (tipo_entrega = 'domicilio' AND direccion IS NOT NULL AND length(btrim(direccion)) > 0)
        OR (tipo_entrega = 'recogida' AND direccion IS NULL AND barrio IS NULL)
    )
);

CREATE TABLE pedido_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES productos(id) ON DELETE SET NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    precio_unitario_cop INTEGER NOT NULL CHECK (precio_unitario_cop > 0),
    cantidad SMALLINT NOT NULL CHECK (cantidad BETWEEN 1 AND 99),
    subtotal_cop BIGINT NOT NULL CHECK (subtotal_cop > 0),
    CONSTRAINT pedido_items_subtotal_correcto CHECK (
        subtotal_cop = precio_unitario_cop::BIGINT * cantidad
    )
);

CREATE TABLE historial_estados_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
    estado_anterior estado_pedido,
    estado_nuevo estado_pedido NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT historial_estado_inicial CHECK (
        estado_anterior IS NOT NULL OR estado_nuevo = 'pendiente'
    )
);

CREATE TABLE mensajes_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    telefono VARCHAR(30),
    mensaje VARCHAR(2000) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE suscriptores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(254) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX suscriptores_correo_unico ON suscriptores (LOWER(correo));
CREATE INDEX productos_categoria_id_idx ON productos (categoria_id);
CREATE INDEX productos_disponible_idx ON productos (disponible);
CREATE INDEX clientes_telefono_idx ON clientes (telefono);
CREATE INDEX pedidos_estado_idx ON pedidos (estado);
CREATE INDEX pedidos_creado_en_idx ON pedidos (creado_en DESC);
CREATE INDEX pedidos_cliente_id_creado_en_idx ON pedidos (cliente_id, creado_en DESC);
CREATE INDEX pedido_items_producto_id_idx ON pedido_items (producto_id);
CREATE INDEX historial_pedido_fecha_idx ON historial_estados_pedido (pedido_id, fecha DESC);
CREATE INDEX mensajes_contacto_creado_en_idx ON mensajes_contacto (creado_en DESC);

CREATE FUNCTION actualizar_fecha_modificacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.actualizado_en = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER productos_actualizado_en
BEFORE UPDATE ON productos
FOR EACH ROW EXECUTE FUNCTION actualizar_fecha_modificacion();

CREATE TRIGGER clientes_actualizado_en
BEFORE UPDATE ON clientes
FOR EACH ROW EXECUTE FUNCTION actualizar_fecha_modificacion();

CREATE TRIGGER pedidos_actualizado_en
BEFORE UPDATE ON pedidos
FOR EACH ROW EXECUTE FUNCTION actualizar_fecha_modificacion();

GRANT USAGE ON SCHEMA public TO turilli_app;
GRANT SELECT ON productos, categorias TO turilli_app;
GRANT SELECT, INSERT, UPDATE ON clientes TO turilli_app;
GRANT INSERT ON pedidos, pedido_items, historial_estados_pedido,
    mensajes_contacto, suscriptores TO turilli_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO turilli_app;

COMMIT;
